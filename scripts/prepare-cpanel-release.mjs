import { cp, mkdir, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
const root = process.cwd();
const output = path.resolve(process.argv[2] || '.release');
await mkdir(output);
const result = spawnSync(process.execPath, ['server/scripts/prepare-runtime-package.mjs', path.join(output, 'server')], { stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status || 1);
await mkdir(path.join(output, 'server/dist'));
await cp('server/dist/src', path.join(output, 'server/dist/src'), { recursive: true, filter: file => !file.endsWith('.map') });
await cp('server/migrations', path.join(output, 'server/migrations'), { recursive: true });
await mkdir(path.join(output, 'server/scripts'));
for (const file of ['migrate.mjs', 'import-open-data.mjs', 'repair-cpanel.mjs', 'setup-production.mjs']) await cp(path.join(root, 'server/scripts', file), path.join(output, 'server/scripts', file));
await writeFile(path.join(output, 'server/app.cjs'), "import('./dist/src/index.js').catch(error => { console.error('[leadflow startup]', error); process.exitCode = 1; });\n");
await cp('dist', path.join(output, 'web'), { recursive: true });
await mkdir(path.join(output, 'scripts'));
await cp('scripts/deploy-cpanel.sh', path.join(output, 'scripts/deploy-cpanel.sh'));
await writeFile(path.join(output, '.cpanel.yml'), '---\ndeployment:\n  tasks:\n    - /bin/bash scripts/deploy-cpanel.sh\n');
await cp('docs/github-namecheap-setup.md', path.join(output, 'README.md'));
console.log('Prebuilt cPanel release ready at ' + output);
